--
--  Это единственный файл, в котором определено, что такое
--  «главная метрика» проекта. Всё остальное (паспорт, дашборд на З10,
--  виджет на З11) обязано давать то же число.
--
--  ОПРЕДЕЛЕНИЕ
--  ───────────
--  Оборот доставленных заказов (GMV_delivered)
--      = SUM(fact_sales.amount) по заказам со статусом `delivered`, BRL.
--
--      НЕ включает freight_value   — доставка это затрата, а не выручка;
--      НЕ включает отменённые      — `canceled` (625) и `unavailable`
--                                    (609) деньги до покупателя не довели;
--      НЕ включает оплату          — payment_value_order может не совпадать
--                                    со стоимостью позиций (рассрочка,
--                                    частичные платежи), а «оборот» — это
--                                    стоимость проданного.
--
-- =====================================================================

SELECT
    'GMV_delivered'                     AS metric_name,
    'Сумма amount по заказам в статусе delivered, BRL'
                                        AS metric_definition,
    SUM(amount)                         AS metric_value,
    COUNT(*)                            AS positions_count,     -- строк факта
    COUNT(DISTINCT order_id)            AS orders_count,        -- заказов
    SUM(qty)                            AS units_count          -- штук
FROM fact_sales
WHERE order_status = 'delivered';
